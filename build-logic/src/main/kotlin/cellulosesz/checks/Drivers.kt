package cellulosesz.checks

import org.gradle.api.artifacts.MinimalExternalModuleDependency
import org.gradle.api.artifacts.VersionCatalog
import org.gradle.api.provider.Provider
import java.io.File
import java.security.MessageDigest
import java.util.*

/**
 * `[database] type` -> version catalog alias, in manifest and bundle order. The backend names must
 * match `DatabaseType` lowercased, because the runtime manifest is keyed by them.
 */
val DRIVER_ALIASES: List<Pair<String, String>> = listOf(
    "sqlite" to "sqlite-jdbc",
    "h2" to "h2",
    "postgresql" to "postgresql",
    "mariadb" to "mariadb",
    "mysql" to "mysql",
)

/** One driver artifact, derived from the version catalog. */
class DriverCoordinate(
    val backend: String,
    val group: String,
    val module: String,
    val version: String,
) {

    val fileName: String = "$module-$version.jar"
    val notation: String = "$group:$module:$version"
    val repositoryPath: String = "${group.replace('.', '/')}/$module/$version/$fileName"

}

/** A manifest row: what the runtime is allowed to download, and what it must hash to. */
class DriverManifestEntry(
    val backend: String,
    val notation: String,
    val fileName: String,
    val size: Long,
    val sha256: String,
    val repositoryPath: String,
)

/** Resolves every driver coordinate from the version catalog; a missing alias fails the build. */
fun driverCoordinates(catalog: VersionCatalog): List<DriverCoordinate> =
    DRIVER_ALIASES.map { (backend, alias) ->
        val dependency: Provider<MinimalExternalModuleDependency> = catalog.findLibrary(alias)
                .orElseThrow {
                    IllegalStateException("version catalog has no library alias '$alias'")
                }
        val module = dependency.get().module
        DriverCoordinate(
            backend = backend,
            group = module.group,
            module = module.name,
            version = dependency.get().versionConstraint.requiredVersion,
        )
    }

fun sha256Of(file: File): String {
    val digest = MessageDigest.getInstance("SHA-256")
    file.inputStream().use { input ->
        val buffer = ByteArray(DEFAULT_BUFFER_SIZE)
        while (true) {
            val read = input.read(buffer)
            if (read < 0) {
                break
            }
            digest.update(buffer, 0, read)
        }
    }
    return HexFormat.of().formatHex(digest.digest())
}

/**
 * Writes `backend=coordinate|fileName|size|sha256|repositoryPath`. Line endings are fixed so the
 * generated resource stays byte-identical across hosts.
 */
fun writeDriverManifest(file: File, entries: List<DriverManifestEntry>) {
    val header = "# Generated by :modules:foundation:generateDriverManifest - do not edit.\n" +
            "# backend=coordinate|fileName|size|sha256|repositoryPath"
    val rows = entries.joinToString("\n") { entry ->
        "${entry.backend}=${entry.notation}|${entry.fileName}|${entry.size}|" +
                "${entry.sha256}|${entry.repositoryPath}"
    }
    file.parentFile?.mkdirs()
    file.writeText("$header\n$rows\n")
}

fun readDriverManifest(file: File): List<DriverManifestEntry> =
    file.readLines()
            .filter { it.isNotBlank() && !it.startsWith("#") }
            .map { line ->
                val separator = line.indexOf('=')
                require(separator > 0) { "malformed driver manifest line: $line" }
                val backend = line.substring(0, separator)
                val parts = line.substring(separator + 1).split('|')
                require(parts.size == 5) { "malformed driver manifest entry for '$backend'" }
                DriverManifestEntry(
                    backend = backend,
                    notation = parts[0],
                    fileName = parts[1],
                    size = parts[2].toLong(),
                    sha256 = parts[3],
                    repositoryPath = parts[4],
                )
            }

/** The instructions shipped inside the offline bundle archive. */
fun renderDriverBundleReadme(entries: List<DriverManifestEntry>): String {
    val intro = """
        CellulosesZ - offline JDBC driver bundle
        ========================================

        The JDBC drivers CellulosesZ uses, packaged for servers that cannot reach
        Maven Central.

        Install
        -------
          1. Stop the server.
          2. Unpack this archive into the server root:

               unzip cellulosesz-drivers-<version>.zip -d <server root>

             The jars then live in <server root>/cellulosesz/drivers/.
          3. Start the server.

        Only the jar matching your [database] type is used; the others are ignored,
        so keeping all of them unpacked is fine.
    """.trimIndent()

    val columns = "  ${"backend".padEnd(12)}" +
            "file".padEnd(36) +
            "${"bytes".padStart(10)}  sha256"
    val rule = "  ${"-".repeat(104)}"
    val rows = entries.sortedBy { it.backend }.joinToString("\n") { entry ->
        "  ${entry.backend.padEnd(12)}" +
                entry.fileName.padEnd(36) +
                entry.size.toString().padStart(10) +
                "  ${entry.sha256}"
    }

    return "$intro\n\n$columns\n$rule\n$rows\n"
}
